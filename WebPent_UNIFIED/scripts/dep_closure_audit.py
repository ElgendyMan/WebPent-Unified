#!/usr/bin/env python3
"""Single published dependency-closure security audit (audit D-01 remediation).

PUBLISHED CLOSURE DEFINITION (the only one used from 2026-10-05 v2 onward):

    The project runtime closure C is the union of
      (a) every direct dependency declared in pyproject.toml
          [project].dependencies, and
      (b) the full transitive dependency closure of (a) as resolved from the
          INSTALLED environment's package metadata (importlib.metadata
          Requires-Dist), skipping requires that are gated on extras.

    The audit runs `pip-audit -r <closure requirements file> --no-deps`,
    i.e. exactly the pinned versions of C and nothing else. venv-wide
    findings outside C are reported as a count only and are out of scope.

This replaces the previous sprint's inconsistent scoping (before-count over
a broad closure, after-count over direct deps only), which the hostile audit
flagged as defect D-01.

Usage:
    python scripts/dep_closure_audit.py [--json OUT.json]

Outputs:
    - prints the closure package list and any findings
    - writes <project root>/deliverables/requirements_closure.txt
    - writes JSON artifact (default deliverables/dep_closure_audit.json)
Exit codes: 0 = closure clean, 1 = closure has findings, 2 = usage/env error.
Accepted residuals must be listed in ACCEPTED_RESIDUALS below with a reason;
they are reported as "accepted_residual" and do not fail the gate.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import tomllib
from importlib import metadata
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
PYPROJECT = PROJECT_ROOT / "pyproject.toml"
DELIVERABLES = PROJECT_ROOT / "deliverables"

# Residuals explicitly accepted and documented in EVIDENCE_REPORT_20261005.md.
# Each entry must name the exact distribution and the honest reason.
ACCEPTED_RESIDUALS = {
    "chromadb": (
        "4 advisories; fixes only in breaking 2.x line; project pins <2.0 "
        "(upgrade tracked as a separate sprint). Accepted and documented."
    ),
}


def _norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def direct_deps() -> list[str]:
    data = tomllib.loads(PYPROJECT.read_text())
    deps = []
    for dep in data["project"]["dependencies"]:
        name = re.split(r"[><=!~;\[ ]", dep.strip(), maxsplit=1)[0]
        deps.append(_norm(name))
    return sorted(set(deps))


def transitive_closure(direct: list[str]) -> dict[str, str]:
    """BFS over installed metadata. Returns {normalised_name: version}."""
    seen: dict[str, str] = {}
    queue = list(direct)
    skipped_no_dist: list[str] = []
    while queue:
        name = queue.pop(0)
        if name in seen:
            continue
        try:
            dist = metadata.distribution(name)
        except metadata.PackageNotFoundError:
            skipped_no_dist.append(name)
            continue
        seen[name] = dist.version
        for req in (dist.requires or []):
            # skip extras-gated and env-marker-gated requirements that do
            # not apply to this environment
            if ";" in req:
                dep_part, marker = req.split(";", 1)
                if "extra ==" in marker:
                    continue
                try:
                    from packaging.markers import Marker
                    if not Marker(marker.strip()).evaluate():
                        continue
                except Exception:
                    pass  # unparseable marker: keep the dep (conservative)
            else:
                dep_part = req
            dep_name = re.split(r"[><=!~;\[ ]", dep_part.strip(), maxsplit=1)[0]
            if dep_name:
                queue.append(_norm(dep_name))
    if skipped_no_dist:
        print(
            f"WARNING: declared deps not found installed (excluded from C): "
            f"{sorted(set(skipped_no_dist))}",
            file=sys.stderr,
        )
    return seen


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--json", default=str(DELIVERABLES / "dep_closure_audit.json"))
    args = parser.parse_args()

    DELIVERABLES.mkdir(exist_ok=True)
    direct = direct_deps()
    closure = transitive_closure(direct)
    direct_set = set(direct)

    closure_reqs = DELIVERABLES / "requirements_closure.txt"
    closure_reqs.write_text(
        "# Generated by scripts/dep_closure_audit.py — project runtime closure C\n"
        "# Definition: pyproject.toml [project].dependencies + installed transitive\n"
        "# closure (extras skipped). Audited with: pip-audit -r this file --no-deps\n"
        + "\n".join(f"{n}=={v.split('+')[0]}" for n, v in sorted(closure.items()))
        + "\n"
    )

    print(f"Closure C: {len(closure)} packages ({len(direct_set)} direct + "
          f"{len(closure) - len(direct_set)} transitive)")
    print(f"Written: {closure_reqs}")

    audit = subprocess.run(
        [sys.executable, "-m", "pip_audit", "-r", str(closure_reqs),
         "--no-deps", "-f", "json", "-o", str(DELIVERABLES / "_pip_audit_closure_raw.json")],
        capture_output=True, text=True,
    )
    if audit.returncode != 0 and not (DELIVERABLES / "_pip_audit_closure_raw.json").exists():
        print(f"pip-audit failed: {audit.stderr[-2000:]}", file=sys.stderr)
        return 2
    # NOTE: pip-audit exits 1 when findings exist — that is a valid result,
    # not a tool failure. Only a missing output file means failure.

    raw = json.loads((DELIVERABLES / "_pip_audit_closure_raw.json").read_text())
    items = raw.get("dependencies", raw) if isinstance(raw, dict) else raw
    findings, seen_ids = [], set()
    for item in items:
        for vuln in item.get("vulns", []):
            key = (item["name"], vuln["id"])
            if key in seen_ids:
                continue  # dedup (pip-audit can emit the same advisory twice)
            seen_ids.add(key)
            findings.append({
                "package": item["name"],
                "version": item["version"],
                "id": vuln["id"],
                "fix_versions": vuln.get("fix_versions", []),
            })

    open_findings, accepted = [], []
    for f in findings:
        (accepted if _norm(f["package"]) in ACCEPTED_RESIDUALS
         else open_findings).append(f)

    result = {
        "definition": (
            "C = pyproject.toml [project].dependencies + installed transitive "
            "closure (extras skipped); audited via pip-audit -r "
            "requirements_closure.txt --no-deps"
        ),
        "closure_size": len(closure),
        "direct_deps": direct,
        "closure_packages": sorted(closure),
        "open_findings": open_findings,
        "accepted_residuals": [
            {**f, "reason": ACCEPTED_RESIDUALS[_norm(f["package"])]}
            for f in accepted
        ],
        "verdict": "CLEAN" if not open_findings else "FINDINGS",
    }
    out = Path(args.json)
    out.write_text(json.dumps(result, indent=2) + "\n")

    print(f"\nOpen findings (NOT accepted): {len(open_findings)}")
    for f in open_findings:
        print(f"  {f['package']} {f['version']} {f['id']} fixes={f['fix_versions']}")
    print(f"Accepted residual packages: {len({f['package'] for f in accepted})} "
          f"({len(accepted)} advisories)")
    shown = set()
    for f in accepted:
        if f["package"] in shown:
            continue
        shown.add(f["package"])
        n = len([x for x in findings if x["package"] == f["package"]])
        print(f"  {f['package']} {f['version']} ({n} advisories) — accepted: "
              f"{ACCEPTED_RESIDUALS[_norm(f['package'])][:80]}")
    print(f"\nJSON artifact: {out}")
    print(f"VERDICT: {result['verdict']}")
    return 0 if not open_findings else 1


if __name__ == "__main__":
    raise SystemExit(main())
