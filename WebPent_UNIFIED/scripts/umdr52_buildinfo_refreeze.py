    first = fixes.index(umdr42[0])
    seen = False
    deduped = []
    for f in fixes:
        if "UMDR42-closure" in str(f):
            if seen:
                continue
            seen = True
        deduped.append(f)
    bi["fixes_applied"] = deduped
    bi.setdefault("fixes_applied_notes", []).append(
        "UMDR52 (2026-11-28): the UMDR42-closure line duplicated "
        + str(len(umdr42) - 1) + " times — deduplicated to one "
        "occurrence at this re-bind (declared, content unchanged)")

