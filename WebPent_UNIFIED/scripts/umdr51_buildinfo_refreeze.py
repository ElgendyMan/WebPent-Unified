from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BI = ROOT / "BUILD_INFO.json"
EV = ROOT / ".webpent-evidence" / "FULL_SUITE_EVIDENCE.json"

BATTERY_COMMIT = "ee4832626ebeade9a3d9bb396bdadeb133cff5aa"

bi = json.loads(BI.read_text())
ev = json.loads(EV.read_text())
acc = ev["accounting_v3"]
assert ev["source_commit"] == BATTERY_COMMIT, (
    f"battery commit mismatch: {ev['source_commit']}")
assert ev["tree_clean"] is True, "battery tree not clean"
assert acc["started_items"] == acc["collected_items"] == 9947
assert acc["outcomes"]["failed"] == 7, acc["outcomes"]

now = datetime.now(timezone.utc).isoformat()
bi["build_date"] = now
bi["package_version"] = "0.49.0"
bi["suite_count"] = acc["started_items"]
bi["suite_evidence"] = (
    "current-run full-suite evidence on this branch tip: UM-DR-51 "
    "v0.49.0 re-freeze battery at ee48326 (tree_clean=TRUE) — 9947 "
    "collected / 9947 started (v3 started_items, invariants_all_true, "
    "cross-check all_agree) / 9927 passed / 7 failed — the seven "
    "failures are the re-bind gates themselves (the G02 inventory "
    "drift from the window's four edited files — regenerated by "
    "scripts/regen_direct_io_inventory_umdr51.py, pin UNCHANGED "
    "29/25 — plus the version-source and BUILD_INFO-binding gates "
    "for 0.48.0->0.49.0), satisfied BY THIS re-bind commit; "
    "accounting_consistent per the §6 contract"
)
prov = bi["provenance"]
prov["source_revision"] = BATTERY_COMMIT
prov["tested_revision"] = BATTERY_COMMIT
prov["evidence_revision"] = BATTERY_COMMIT
prov["package_version"] = "0.49.0"
prov["build_date"] = now
pub = prov.get("publication") or {}
prov["publication"] = {
    **pub,
    "published": False,
    "release_tag": "v0.49.0",
    "note": (
        "v0.49.0 publication in progress from main on the UM-DR-51 "
        "re-bind: CI green on the exact tip -> tag -> Release + "
        "PUBLICATION.json (the window-50 e7c5e3a pattern)"
    ),
}
vic = bi.get("version_identity_contract") or {}
if isinstance(vic, dict):
    vic["package_version"] = "0.49.0"
    prev = dict(vic.get("previous_release") or {})
    vic["previous_release"] = {
        **prev,
        "label": "v0.48.0-UMDR50",
        "package_version": "0.48.0",
        "source_revision": "e7c5e3ab71edb88fee7d7ab97f8206bb6cbca0e5",
    }

BI.write_text(json.dumps(bi, indent=2) + "\n")
print("BUILD_INFO re-frozen onto", BATTERY_COMMIT[:7],
      "| version 0.49.0 | suite_count", bi["suite_count"])
