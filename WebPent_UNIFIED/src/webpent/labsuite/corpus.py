"""L7 lab corpus roster.

Three blocks, generated by the lab's own generator (no fixture code):

- DEV 101-104: the only block that may drive failure analysis and
  engine fixes (mission section 6).
- HELD-OUT 201-203 and 211-213: scored only after investigation
  finishes; if these outcomes ever influence an implementation
  decision, a fresh evaluation set is generated before final claims.
- NEGATIVE 301-302: correctly secured deployments across every family
  (all enforcement on); any confirmation there is a false positive.
"""
from __future__ import annotations

from webpent.labsuite.lab_target import (
    LabSpec,
    generate_lab_instance,
)

DEV_SEEDS = (101, 102, 103, 104)
HELDOUT_SEEDS = (201, 202, 203, 211, 212, 213)
NEGATIVE_SEEDS = (301, 302)

SECURE_PROFILE = {
    "identity_read_enforced": True,
    "identity_mutation_enforced": True,
    "checkout_impl": "authoritative",
    "spend_impl": "cumulative",
    "grant_impl": "consumed",
    "workflow_identity_enforced": True,
    "order_enforced": True,
}


def lab_instance(
    seed: int, *, instance_id: str | None = None,
) -> LabSpec:
    """Build a corpus member. Negative seeds force the secured profile
    over whatever the seed rotation picked."""
    spec = generate_lab_instance(
        seed, instance_id=instance_id or f"lab-{seed}")
    if seed in NEGATIVE_SEEDS:
        spec = generate_lab_instance(
            seed, instance_id=instance_id or f"lab-{seed}",
            profile=SECURE_PROFILE)
    return spec


def dev_block() -> list[LabSpec]:
    return [lab_instance(seed) for seed in DEV_SEEDS]


def heldout_block() -> list[LabSpec]:
    return [lab_instance(seed) for seed in HELDOUT_SEEDS]


def negative_block() -> list[LabSpec]:
    return [lab_instance(seed) for seed in NEGATIVE_SEEDS]
